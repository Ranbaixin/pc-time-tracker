"""Portable per-user Windows autostart registration."""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Protocol

REG_KEY = r"Software\Microsoft\Windows\CurrentVersion\Run"
REG_VALUE = "PCTimeTracker"


class Registry(Protocol):
    def get(self) -> str | None: ...
    def set(self, value: str) -> None: ...
    def delete(self) -> None: ...


class WindowsRunRegistry:
    def get(self) -> str | None:
        import winreg

        try:
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER, REG_KEY, 0, winreg.KEY_READ) as key:
                value, _ = winreg.QueryValueEx(key, REG_VALUE)
                return str(value)
        except FileNotFoundError:
            return None

    def set(self, value: str) -> None:
        import winreg

        with winreg.CreateKeyEx(
            winreg.HKEY_CURRENT_USER, REG_KEY, 0, winreg.KEY_SET_VALUE
        ) as key:
            winreg.SetValueEx(key, REG_VALUE, 0, winreg.REG_SZ, value)

    def delete(self) -> None:
        import winreg

        try:
            with winreg.OpenKey(
                winreg.HKEY_CURRENT_USER, REG_KEY, 0, winreg.KEY_SET_VALUE
            ) as key:
                winreg.DeleteValue(key, REG_VALUE)
        except FileNotFoundError:
            return


class AutostartService:
    def __init__(
        self,
        project_dir: Path,
        executable: Path,
        registry: Registry,
        wscript: Path,
    ):
        self.project_dir = project_dir.resolve()
        self.executable = executable
        self.registry = registry
        self.wscript = wscript
        self.launcher = self.project_dir / "data" / "PCTimeTracker-autostart.vbs"

    def enable(self) -> Path:
        self.launcher.parent.mkdir(parents=True, exist_ok=True)
        project = str(self.project_dir).replace('"', '""')
        # WScript already hides the child window. Keep the console-capable
        # interpreter because the CLI and Uvicorn may write to stdout/stderr
        # during startup; those streams are absent under pythonw.exe.
        python = str(self.executable).replace('"', '""')
        content = (
            "' Generated by PC Time Tracker.\n"
            'Set WshShell = CreateObject("WScript.Shell")\n'
            f'WshShell.CurrentDirectory = "{project}"\n'
            f'WshShell.Run Chr(34) & "{python}" & Chr(34) & " -m src.main run", 0, False\n'
        )
        temp = self.launcher.with_suffix(".tmp")
        # Windows Script Host rejects UTF-8 BOM scripts on some supported
        # Windows installations. UTF-16 keeps non-ASCII paths portable and is
        # natively recognized by both wscript.exe and cscript.exe.
        temp.write_text(content, encoding="utf-16")
        os.replace(temp, self.launcher)
        self.registry.set(f'"{self.wscript}" "{self.launcher}"')
        return self.launcher

    def disable(self) -> None:
        self.registry.delete()
        self.launcher.unlink(missing_ok=True)

    def is_enabled(self) -> bool:
        value = self.registry.get()
        return bool(value and str(self.launcher) in value and self.launcher.exists())


def get_autostart_service() -> AutostartService:
    project = Path(__file__).resolve().parent.parent
    wscript = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "wscript.exe"
    return AutostartService(project, Path(sys.executable), WindowsRunRegistry(), wscript)
